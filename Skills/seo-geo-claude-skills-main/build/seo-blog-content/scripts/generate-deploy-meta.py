#!/usr/bin/env python3
"""Generate programmer-ready SEO deploy artifacts for all published blog articles.

Outputs:
- <article>/head.html      : clean <head> snippet (meta tags, comments stripped) + JSON-LD <script>
- SEO/Blog/seo-meta.json   : one machine-readable file, slug -> all SEO fields + jsonld array

The programmer injects head.html into the page <head>, OR consumes seo-meta.json
programmatically (Next.js metadata, SSR, QuickCreator API, etc.).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

BLOG = Path(__file__).resolve().parents[5] / "SEO" / "Blog"
COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)


def pillar_dirs() -> list[Path]:
    return sorted(p for p in BLOG.glob("pillar[0-9]*-*") if p.is_dir() and " copy" not in p.name)


def clean_meta_tags(html: str) -> str:
    html = COMMENT_RE.sub("", html)
    lines = [ln.rstrip() for ln in html.splitlines()]
    out, blank = [], False
    for ln in lines:
        if ln.strip() == "":
            if not blank and out:
                out.append("")
            blank = True
        else:
            out.append(ln)
            blank = False
    return "\n".join(out).strip()


def one(pat: str, text: str) -> str:
    m = re.search(pat, text)
    return (m.group(1) if m else "").replace("&quot;", '"').strip()


def all_of(pat: str, text: str) -> list[str]:
    return [m.replace("&quot;", '"').strip() for m in re.findall(pat, text)]


def build_head_html(slug: str, meta_clean: str, schema_text: str) -> str:
    return (
        f"<!-- SEO head for /blog/{slug} - generated by generate-deploy-meta.py; do not hand-edit -->\n"
        f"{meta_clean}\n\n"
        f'<script type="application/ld+json">\n{schema_text.strip()}\n</script>\n'
    )


def extract_record(slug: str, h: str, schema: list) -> dict:
    return {
        "slug": slug,
        "url": one(r'<link rel="canonical" href="([^"]+)"', h),
        "title": one(r"<title>([^<]+)</title>", h),
        "meta_description": one(r'<meta name="description" content="([^"]+)"', h),
        "canonical": one(r'<link rel="canonical" href="([^"]+)"', h),
        "robots": one(r'<meta name="robots" content="([^"]+)"', h),
        "hreflang": {
            "en": one(r'hreflang="en" href="([^"]+)"', h),
            "zh-CN": one(r'hreflang="zh-CN" href="([^"]+)"', h),
            "x-default": one(r'hreflang="x-default" href="([^"]+)"', h),
        },
        "og": {
            "type": one(r'<meta property="og:type" content="([^"]+)"', h),
            "url": one(r'<meta property="og:url" content="([^"]+)"', h),
            "title": one(r'<meta property="og:title" content="([^"]+)"', h),
            "description": one(r'<meta property="og:description" content="([^"]+)"', h),
            "image": one(r'<meta property="og:image" content="([^"]+)"', h),
            "image_alt": one(r'<meta property="og:image:alt" content="([^"]+)"', h),
            "site_name": one(r'<meta property="og:site_name" content="([^"]+)"', h),
            "locale": one(r'<meta property="og:locale" content="([^"]+)"', h),
        },
        "twitter": {
            "card": one(r'<meta name="twitter:card" content="([^"]+)"', h),
            "site": one(r'<meta name="twitter:site" content="([^"]+)"', h),
            "title": one(r'<meta name="twitter:title" content="([^"]+)"', h),
            "description": one(r'<meta name="twitter:description" content="([^"]+)"', h),
            "image": one(r'<meta name="twitter:image" content="([^"]+)"', h),
        },
        "article": {
            "published_time": one(r'<meta property="article:published_time" content="([^"]+)"', h),
            "modified_time": one(r'<meta property="article:modified_time" content="([^"]+)"', h),
            "section": one(r'<meta property="article:section" content="([^"]+)"', h),
            "tags": all_of(r'<meta property="article:tag" content="([^"]+)"', h),
        },
        "jsonld": schema,
    }


def main() -> None:
    records = []
    heads = 0
    for pillar in pillar_dirs():
        for art in sorted(pillar.glob("[0-9][0-9][0-9]-*/")):
            meta_path = art / "meta-tags.html"
            schema_path = art / "schema.json"
            if not meta_path.is_file():
                continue
            h = meta_path.read_text(encoding="utf-8")
            slug = one(
                r'<link rel="canonical" href="https://infinisynapse\.com/en/blog/([^"]+)"',
                h,
            )
            if not slug:
                slug = one(
                    r'<link rel="canonical" href="https://infinisynapse\.cn/blog/([^"]+)"',
                    h,
                )
            schema_text = schema_path.read_text(encoding="utf-8") if schema_path.is_file() else "[]"
            try:
                schema = json.loads(schema_text)
            except json.JSONDecodeError:
                schema = []

            head_html = build_head_html(slug, clean_meta_tags(h), schema_text)
            (art / "head.html").write_text(head_html, encoding="utf-8")
            heads += 1

            records.append({"id": art.name[:3], "folder": art.name,
                             "source_path": f"SEO/Blog/{pillar.name}/{art.name}",
                             **extract_record(slug, h, schema)})

    records.sort(key=lambda r: r["id"])
    bundle = {
        "_comment": "Programmer-ready SEO metadata for all published blog articles. Inject per slug.",
        "_usage": "Use head.html per article folder for raw injection, or this JSON for "
                  "programmatic metadata (Next.js generateMetadata, SSR, CMS API).",
        "_generated_by": "SEO/Blog/generate-deploy-meta.py",
        "count": len(records),
        "articles": records,
    }
    out = BLOG / "seo-meta.json"
    out.write_text(json.dumps(bundle, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {heads} head.html files")
    print(f"Wrote {out} ({len(records)} records)")


if __name__ == "__main__":
    main()
